// The bubbly typeface: a chunky rounded sans in the same 5x8 cell as the
// original font (font.go), redrawn rather than resized. It shipped as the
// "modern" style; it reads as more 8-bit than clean, so it was renamed to what
// it is.
//
// "Bubbly" is not the original font at a smaller scale. It is a deliberately
// different typeface, and the difference is structural, so it survives the two
// of them being drawn at the same pixel size:
//
//   - A taller x-height. Lowercase letters run from row 1 to row 6 instead of
//     row 2 to row 6, so a lowercase word reads a notch taller and denser than
//     the retro face. Capitals, digits and the baseline are unchanged from
//     font.go, so mixed case still sits on the same line.
//   - Uniform single-pixel strokes. The heavier letters are thinned down: M
//     drops the retro's double-wide centre column, and every stem elsewhere
//     is one column of ink.
//   - Cleaner details on the letters that carry a face's character: a closed
//     single-storey 'a' instead of the retro flag, a straight-shouldered 'g',
//     a plain 's', and a ring-shaped '@'. Everything else is the same
//     skeleton as font.go — the two faces are siblings, not strangers.
//
// Glyph metrics are identical to the retro font (5x8, one-pixel advance gap,
// baseline row 6), so every measurement in internal/ui works for either face;
// only the bitmap differs.

// bubbleGlyphFor returns the bubbly bitmap for r, with the same repertoire and
// the same missing-glyph convention as the retro face.
func bubbleGlyphFor(r rune) glyph {
	if r < glyphFirst || r > glyphLast {
		return missingGlyph
	}
	return bubbleGlyphs[r-glyphFirst]
}

// BubblyGlyphFor returns the bubbly face's bitmap for r — the sharp geometric
// sans used by the "bubbly" theme. Same cell, same metrics and same
// repertoire as [GlyphFor], so either accessor can be swapped in without
// touching any layout code.
func BubblyGlyphFor(r rune) Glyph { return bubbleGlyphFor(r) }

